// Bundles the embed script and hands it to the Worker as a string (src/generated/widget.ts).
import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'

const bundle = async (entry) =>
  (await build({ entryPoints: [entry], bundle: true, minify: true, format: 'iife', target: 'es2020', write: false })).outputFiles[0].text
const js = await bundle('src/widget/widget.ts')
const schedule = await bundle('src/widget/schedule.ts')
mkdirSync('src/generated', { recursive: true })
writeFileSync(
  'src/generated/widget.ts',
  `// Generated by scripts/build-widget.mjs. Do not edit.\nexport const WIDGET_JS = ${JSON.stringify(js)}\nexport const SCHEDULE_JS = ${JSON.stringify(schedule)}\n`,
)
console.log(`widget: ${(js.length / 1024).toFixed(1)} KB, schedule: ${(schedule.length / 1024).toFixed(1)} KB`)
