// Bundles the embed script and hands it to the Worker as a string (src/generated/widget.ts).
import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'

const out = await build({ entryPoints: ['src/widget/widget.ts'], bundle: true, minify: true, format: 'iife', target: 'es2020', write: false })
const js = out.outputFiles[0].text
mkdirSync('src/generated', { recursive: true })
writeFileSync('src/generated/widget.ts', `// Generated by scripts/build-widget.mjs. Do not edit.\nexport const WIDGET_JS = ${JSON.stringify(js)}\n`)
console.log(`widget: ${(js.length / 1024).toFixed(1)} KB`)
